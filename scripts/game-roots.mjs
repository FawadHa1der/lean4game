#!/usr/bin/env node
// The modules lean4game needs from the kernel's packs, read from the import
// headers of what the lanes compile: every catalog game, GameServer (server/)
// and lean-i18n (vendor/i18n), each walked from the root its compile starts at
// (wasm/build-from-source.sh, wasm/scripts/compile-pkg.py), so a file nothing
// imports does not count. Written to wasm/mathlib-roots.txt in the format of the
// kernel's mathlib-extra-roots.txt: one module per line, `# who imports it`.
//
// It keeps every direct import that is neither the tree's own, nor one of the
// trees above, nor core: Init, Lean and Std, and Lake, which the trees lane takes
// from the native compiler and no Mathlib build can name as a target. It keeps
// imports the essential pack holds today too: the pack is the closure of these
// minus essential, the same with or without them, and a narrower essential then
// cannot silently break a game.
//
// The file is what lean4game hands the kernel. The kernel's own hand-kept list
// decides what its packs hold until the kernel adopts this file, so a module in no
// pack needs someone to get it into that list, then its next pack build (wasm/PORTING.md §4).
//
// Usage: node scripts/game-roots.mjs [--check [--games a,b] [--have <list|dir>]...] [--games-src <dir>]
//   (none)       write wasm/mathlib-roots.txt; needs every catalog game's checkout
//   --check      write nothing; exit 1 naming each difference from the file
//   --games      with --check, only these games, by snapshot name (the lane's
//                --games; the other sources may be absent): their imports must be
//                listed, and whether a listed module is still needed is not asked
//   --have       with --check, what the toolchain can resolve: a module list (the
//                release's lists/*-modules.txt) or a source directory (a vendored
//                module the trees lane compiles). Exit 1 for a listed module in none
//   --games-src  where the catalog's games-src/ checkouts are, when not in this repo
// Exit 0 no difference (--check), 1 a difference, 2 a bad argument or a missing source.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, "..");
const OUT = "wasm/mathlib-roots.txt";
const CORE = new Set(["Init", "Lean", "Std", "Lake"]);
const LIBS = [{ who: "GameServer", dir: path.join(repo, "server"), root: "GameServer" }, { who: "lean-i18n", dir: path.join(repo, "vendor/i18n"), root: "I18n" }];
const HEADER = `# Generated by scripts/game-roots.mjs from the import headers of the catalog games,
# GameServer and lean-i18n: do not edit, rerun it. Each line is a module they import
# directly and do not build themselves, with who imports it. Core is left out.
`;

const die = (message) => { console.error(`game-roots: ${message}`); process.exit(2); };
const compare = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

let check = false, games = null, gamesSrc = null;
const have = [];
const args = process.argv.slice(2);
const value = (i) => (args[i] !== undefined && !args[i].startsWith("--") ? args[i] : die(`${args[i - 1]} needs a value`));
for (let i = 0; i < args.length; i++) {
  if (args[i] === "--check") check = true;
  else if (args[i] === "--games") games = value(++i).split(",");
  else if (args[i] === "--have") have.push(value(++i));
  else if (args[i] === "--games-src") gamesSrc = path.resolve(value(++i));
  else die(`unknown argument ${args[i]} (usage: game-roots.mjs [--check [--games a,b] [--have <list|dir>]...] [--games-src <dir>])`);
}
if (!check && (games || have.length)) die("--games and --have go with --check: the file is written from every game");

/** The imports of a Lean file's header, as Lean parses it: [module] [prelude] ([public] [meta] import [all] Name)*
 * (Lean.Parser.Module.header). It reads tokens outside comments (block comments
 * nest) and stops where that grammar stops: at any other word or order, and at a doc
 * comment, since Lean reads /-! and /-- as tokens. So a file's body is not read. */
function importsOf(text) {
  let i = 0;
  const token = () => {
    for (;;) {
      while (i < text.length && /\s/.test(text[i])) i++;
      if (text.startsWith("--", i)) {
        const eol = text.indexOf("\n", i);
        i = eol < 0 ? text.length : eol;
      } else if (text.startsWith("/--", i) || text.startsWith("/-!", i)) {
        return "";
      } else if (text.startsWith("/-", i)) {
        i += 2;
        for (let depth = 1; depth > 0 && i < text.length;) {
          if (text.startsWith("/-", i)) { depth++; i += 2; }
          else if (text.startsWith("-/", i)) { depth--; i += 2; }
          else i++;
        }
      } else break;
    }
    const start = i;
    while (i < text.length && !/\s/.test(text[i]) && !text.startsWith("--", i) && !text.startsWith("/-", i)) i++;
    return text.slice(start, i);
  };
  const imports = [];
  let t = token();
  if (t === "module") t = token();
  if (t === "prelude") t = token();
  for (;;) {
    if (t === "public") t = token();
    if (t === "meta") t = token();
    if (t !== "import") return imports;
    let name = token();
    if (name === "all") name = token();
    if (!name) return imports;
    imports.push(name.replace(/[«»]/g, ""));
    t = token();
  }
}

const fileOf = (dir, mod) => path.join(dir, `${mod.replaceAll(".", "/")}.lean`);
const isCore = (mod) => CORE.has(mod.split(".")[0]);

/** Every import of `tree` from its root, through its own modules, that it does not build itself. */
function externalImports(tree) {
  const seen = new Set(), todo = [tree.root], external = new Set();
  if (!fs.existsSync(fileOf(tree.dir, tree.root)))
    die(`no ${tree.root}.lean in ${tree.dir} (${tree.who}): wasm/build-from-source.sh --lanes games with no --games clones every game's source (wasm/PORTING.md §4), or pass --games-src`);
  while (todo.length) {
    const mod = todo.pop();
    if (seen.has(mod)) continue;
    seen.add(mod);
    for (const dep of importsOf(fs.readFileSync(fileOf(tree.dir, mod), "utf8"))) {
      if (fs.existsSync(fileOf(tree.dir, dep))) todo.push(dep);
      else if (!isCore(dep) && !LIBS.some((lib) => fs.existsSync(fileOf(lib.dir, dep)))) external.add(dep);
    }
  }
  return external;
}

// The catalog's only reader is games-manifest.mjs: one TSV row per game, snapshot first and src sixth.
const rows = execFileSync(process.execPath, [path.join(here, "games-manifest.mjs"), "--list"], { encoding: "utf8" })
  .split("\n").filter(Boolean).map((line) => line.split("\t"))
  .map((c) => ({ who: c[0], dir: gamesSrc && c[5].startsWith("games-src/") ? path.join(gamesSrc, c[5].slice("games-src/".length)) : path.join(repo, c[5]), root: "Game" }));
const unknown = (games ?? []).filter((g) => !rows.some((r) => r.who === g));
if (unknown.length) die(`--games: no catalog game has the snapshot name ${unknown.join(", ")}`);

// module -> who imports it, from these trees
const whoImports = new Map();
for (const tree of [...rows.filter((r) => !games || games.includes(r.who)), ...LIBS]) {
  for (const mod of externalImports(tree)) whoImports.set(mod, [...(whoImports.get(mod) ?? []), tree.who]);
}
const line = (mod) => `${mod}  # ${whoImports.get(mod).sort(compare).join(", ")}`;
const text = `${HEADER}${[...whoImports.keys()].sort(compare).map(line).join("\n")}\n`;
const scope = `${games ? games.join(", ") : `${rows.length} games`}, GameServer, lean-i18n`;

if (!check) {
  fs.writeFileSync(path.join(repo, OUT), text);
  console.log(`game-roots: wrote ${OUT}: ${whoImports.size} modules from ${scope}`);
  process.exit(0);
}

const outFile = path.join(repo, OUT);
if (!fs.existsSync(outFile)) die(`${OUT} does not exist: run node scripts/game-roots.mjs`);
const fileText = fs.readFileSync(outFile, "utf8");
const file = new Map(fileText.split("\n").filter((l) => l && !l.startsWith("#")).map((l) => [l.split(/\s/)[0], l])); // module -> its line
const rerun = `rerun node scripts/game-roots.mjs and commit ${OUT}`;
const problems = [];
for (const mod of [...whoImports.keys()].sort(compare)) {
  if (!file.has(mod)) problems.push(`+ ${mod} (imported by ${whoImports.get(mod).join(", ")}): a new import, not listed; ${rerun}. A module in no pack also has to get into the kernel's list, then its next pack build (wasm/PORTING.md §4)`);
  else if (!games && file.get(mod) !== line(mod)) problems.push(`~ ${mod}: the file says "${file.get(mod)}", the sources say "${line(mod)}"; ${rerun}`);
}
if (!games) {
  for (const mod of file.keys()) if (!whoImports.has(mod)) problems.push(`- ${mod}: listed, nothing imports it any more; ${rerun}`);
  if (!problems.length && fileText !== text) problems.push(`the file's text is not what the generator writes (edited by hand?); ${rerun}`);
}

if (have.length) {
  const lists = new Set(), dirs = [];
  for (const p of have) {
    const stat = fs.statSync(p, { throwIfNoEntry: false });
    if (!stat) die(`--have ${p}: no such file or directory`);
    if (stat.isDirectory()) dirs.push(p);
    else for (const m of fs.readFileSync(p, "utf8").split(/\s+/)) if (m) lists.add(m);
  }
  const resolves = (mod) => lists.has(mod) || dirs.some((d) => fs.existsSync(fileOf(d, mod)));
  const wanted = new Set(whoImports.keys());
  if (!games) for (const mod of file.keys()) wanted.add(mod);
  for (const mod of [...wanted].sort(compare)) {
    if (!resolves(mod)) problems.push(`! ${mod}${whoImports.has(mod) ? ` (imported by ${whoImports.get(mod).join(", ")})` : ""}: in no pack of the pinned release, so it cannot compile here. Someone has to get it into the kernel's list, then its next pack build (wasm/PORTING.md §4)`);
  }
}

if (problems.length) {
  for (const p of problems) console.error(p);
  console.error(`game-roots: ${problems.length} difference${problems.length === 1 ? "" : "s"} for ${scope}`);
  process.exit(1);
}
console.log(`game-roots: ${OUT} agrees with ${scope} (${whoImports.size} module${whoImports.size === 1 ? "" : "s"})${have.length ? "; every one resolves in the pinned release" : ""}`);
